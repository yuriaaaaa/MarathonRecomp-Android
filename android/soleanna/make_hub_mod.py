#!/usr/bin/env python3
"""Builds the Soleanna Hub mod: a text-Lua town mission that replaces Sonic's first
town mission (scripts/mission/0001/mission.lub) and an archive holding it.

The hub uses the town layout of Sonic's mission 0010 (all nine stage gates and nineteen
mission givers are placed there). Gates and mission givers call ChangeArea with an area
name starting with "hub:", which the native side (MarathonRecomp/os/android/hub_android.cpp)
turns into "open the app chosen for this slot" instead of loading a stage.

Usage: make_hub_mod.py <output mod folder>
Only our own Lua goes into the archive: no game files are copied.
"""
import os, struct, sys, zlib

# event -> slot key, as fired by the warpgate objects in set_mission_0010{a,b,c}.set
GATES = ["wvo", "dtd", "aqa", "csc", "flc", "wap", "rct", "tpj", "kdv"]

# Mission givers in set_mission_0010{a,b,c}.set: (mission, talk id, name id, talk animation, reject line).
# Name/reject ids follow mission 0001's mission_man.lua; givers it doesn't cover use the same pattern.
MEN = [1001, 1003, 1004, 1005, 1006, 1012, 1013, 1014, 1015, 1017, 1018, 1019, 1020, 1022, 1023,
       1026, 1029, 1033, 1035]
ANIM = {1019: "wait_arm", 1006: "talk_aseri", 1035: "talk_sad"}
REJECT = {1008: "_01_5"}

SET_A = "scripts/mission/0010/set_mission_0010a.XML"
SET_B = "scripts/mission/0010/set_mission_0010b.XML"
SET_C = "scripts/mission/0010/set_mission_0010c.XML"


def lua():
    men = []
    for m in MEN:
        n = m - 1000
        talk = "msg_m%d_%03d" % (m, n)
        men.append('  ["%s"] = {slot = "m%d", name = "msg_m%d_n%03d", anim = "%s", accept = "accept_%d", reject = "reject_%d", no = "%s%s"},'
                   % (talk, m, m, n, ANIM.get(m, "talk0"), m, m, talk, REJECT.get(m, "_01_2")))
    events = "\n".join('  ["goto_%s"] = "gate_%s",' % (g, g) for g in GATES)
    return f'''-- Soleanna Hub: Sonic's town as a launcher. Generated by android/soleanna/make_hub_mod.py.
-- Stage gates and mission givers open the Android app chosen for them in the hub's settings.
g_mission_information = {{
  mission_string = "msg_twn_sonic25",
  mission_area = "twn/sonic/a",
  mission_terrain = "stage/twn/a/",
  mission_set_default = "{SET_A}",
  mission_text = "text/msg_twn_sonic.mst",
  mission_is_battle = false,
  mission_area_text = "msg_solleanna_a",
  mission_progress = 0
}}
g_shop = {{
  {{
    message_first = "msg_shop_003",
    message_agree = "msg_shop_005",
    message_buy_item = "msg_shop_006",
    message_cancel_item = "msg_shop_007",
    message_second = "msg_shop_007",
    message_no_money = "msg_shop_008",
    message_end = "msg_shop_012"
  }}
}}
g_message_setuped = ""
g_message_icon = 0
g_name_setuped = ""
c_icon_chat = 0
c_icon_hint = 1
c_icon_mission = 3
g_select_missionman = {{
  {{name = "msg_m1000_001_01_1", event = ""}},
  {{name = "msg_m1000_002_01_1", event = ""}}
}}
g_hub_gates = {{
{events}
}}
g_hub_men = {{
{chr(10).join(men)}
}}
g_hub_accept = {{}}
g_hub_reject = {{}}
for k, v in next, g_hub_men do
  g_hub_accept[v.accept] = v
  g_hub_reject[v.reject] = v
end
script.reload("scripts/mission/0010/mission_talk.lua")
-- Asks the hub to open the app for a slot. Sonic stays where he is.
function hub_open(_ARG_0_, _ARG_1_)
  ChangeArea(_ARG_0_, "hub:" .. _ARG_1_)
end
-- Every upgrade the shop or story gives (player/common.lua c_equip_flag_table: 6000-6020),
-- so Light Speed Dash rows and the like don't block the way to a gate.
g_hub_upgrades_done = false
function hub_unlock_upgrades(_ARG_0_)
  if g_hub_upgrades_done then
    return
  end
  g_hub_upgrades_done = true
  for f = 6000, 6020 do
    if GetGlobalFlag(_ARG_0_, f) == 0 then
      SetGlobalFlag(_ARG_0_, f, 1)
    end
  end
end
function main(_ARG_0_)
  hub_unlock_upgrades(_ARG_0_)
end
function on_talk_icon(_ARG_0_, _ARG_1_)
  if g_hub_men[_ARG_1_] ~= nil then
    g_message_icon = c_icon_mission
  else
    g_message_icon = c_icon_chat
  end
end
function on_goto(_ARG_0_, _ARG_1_)
  local area = g_mission_information.mission_area
  if _ARG_1_ == "goto_a" then
    g_mission_information.mission_terrain = "stage/twn/a/"
    g_mission_information.mission_area = "twn/sonic/a"
    g_mission_information.mission_set_default = "{SET_A}"
    g_mission_information.mission_area_text = "msg_solleanna_a"
  elseif _ARG_1_ == "goto_b" then
    g_mission_information.mission_terrain = "stage/twn/b/"
    g_mission_information.mission_area = "twn/sonic/b"
    g_mission_information.mission_set_default = "{SET_B}"
    g_mission_information.mission_area_text = "msg_solleanna_b"
  elseif _ARG_1_ == "goto_c" then
    g_mission_information.mission_terrain = "stage/twn/c/"
    g_mission_information.mission_area = "twn/sonic/c"
    g_mission_information.mission_set_default = "{SET_C}"
    g_mission_information.mission_area_text = "msg_solleanna_c"
  else
    return
  end
  if area ~= g_mission_information.mission_area then
    ChangeArea(_ARG_0_, g_mission_information.mission_area)
  end
end
function on_event(_ARG_0_, _ARG_1_)
  local gate = g_hub_gates[_ARG_1_]
  if gate ~= nil then
    hub_open(_ARG_0_, gate)
    return
  end
  local man = g_hub_accept[_ARG_1_]
  if man ~= nil then
    hub_open(_ARG_0_, man.slot)
    return
  end
  man = g_hub_reject[_ARG_1_]
  if man ~= nil then
    OpenWindow(_ARG_0_, man.no)
    return
  end
  if _ARG_1_ == "goto_a" or _ARG_1_ == "goto_b" or _ARG_1_ == "goto_c" then
    on_goto(_ARG_0_, _ARG_1_)
  end
end
function on_talk_setup(_ARG_0_, _ARG_1_)
  local man = g_hub_men[_ARG_1_]
  if man ~= nil then
    SetAnimationTalkWith(_ARG_0_, man.anim, "normal")
    g_name_setuped = man.name
    g_message_setuped = _ARG_1_ .. "_01_1"
    g_talk_reuse = 1
    return
  end
  if mission_talk(_ARG_0_, _ARG_1_) == true then
    return
  end
  if _ARG_1_ == "shop" then
    OpenShop(_ARG_0_, "g_shop")
    g_message_setuped = ""
  end
end
function on_talk_oepn(_ARG_0_, _ARG_1_)
end
function on_talk_close(_ARG_0_, _ARG_1_)
  for k, v in next, g_hub_men do
    if _ARG_1_ == k .. "_01_1" then
      g_select_missionman[1].event = v.accept
      g_select_missionman[2].event = v.reject
      OpenSelect(_ARG_0_, "g_select_missionman")
      return
    end
  end
end
function on_hint(_ARG_0_, _ARG_1_)
  g_message_setuped = _ARG_1_
end
function on_goal(_ARG_0_)
end
'''


def u8(files):
    """files: {"xenon/scripts/...": bytes}. Same layout as U8Archive.java writes."""
    root = {}
    for path, data in files.items():
        node = root
        parts = path.split("/")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = data
    order = []  # (name, is_dir, data, parent)

    def flatten(name, node, parent):
        i = len(order)
        order.append([name, isinstance(node, dict), node, parent, 0])
        if isinstance(node, dict):
            for k in node:
                flatten(k, node[k], i)
    flatten("", root, 0)

    def ends(i):
        nxt = i + 1
        if order[i][1]:
            for _ in order[i][2]:
                nxt = ends(nxt)
            order[i][4] = nxt
        return nxt
    ends(0)
    names = bytearray()
    name_off = []
    for n in order:
        name_off.append(len(names))
        names += n[0].encode() + b"\0"
    count = len(order)
    table_len = count * 16 + len(names)
    data_start = (0x20 + table_len + 0x1F) & ~0x1F
    stored, cursor, offs = [], data_start, []
    for n in order:
        if n[1]:
            offs.append(0); stored.append(None); continue
        comp = zlib.compress(n[2], 9) if n[2] else b""
        cursor = (cursor + 0x1F) & ~0x1F
        offs.append(cursor); stored.append(comp); cursor += len(comp)
    out = bytearray(struct.pack(">IIII", 0x55AA382D, 0x20, table_len, data_start))
    out += struct.pack(">IIII", 0xE4F91200, 0x00000402, 0, 0)
    for i, n in enumerate(order):
        if n[1]:
            out += struct.pack(">IIII", (1 << 24) | name_off[i], 0 if i == 0 else n[3], n[4], 0)
        else:
            out += struct.pack(">IIII", name_off[i], offs[i], len(stored[i]), len(n[2]))
    out += names
    for i, n in enumerate(order):
        if n[1]:
            continue
        out += b"\0" * (offs[i] - len(out))
        out += stored[i]
    return bytes(out)


def main():
    dest = sys.argv[1]
    text = lua().encode("latin-1")
    os.makedirs(os.path.join(dest, "xenon", "archives"), exist_ok=True)
    with open(os.path.join(dest, "xenon", "archives", "scripts.arc"), "wb") as f:
        f.write(u8({"xenon/scripts/mission/0001/mission.lub": text}))
    with open(os.path.join(dest, "mod.ini"), "w", newline="\r\n") as f:
        f.write('[Details]\nTitle="Soleanna Hub"\nVersion="0.1"\nAuthor="Soleanna Hub"\n'
                'Description="Sonic\'s town as a launcher: gates and mission givers open your Android games."\n\n'
                '[Filesystem]\nMerge="True"\nPlatform="Xbox 360"\n')
    with open(os.path.join(dest, "hub_mission.lua"), "wb") as f:
        f.write(text)


if __name__ == "__main__":
    main()
